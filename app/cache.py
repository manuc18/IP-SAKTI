"""A cache of answers the pipeline already published, and nothing else.

The free Groq plan caps tokens per minute, and a demo asks the same six
questions repeatedly. Every repetition re-spends the budget on a question the
system has already answered correctly — and when the budget runs out the UI
shows `RATE_LIMITED`, which is a service failure standing where a good answer
used to be.

This module removes the repetition, not the pipeline. What it stores is the
result of one complete run:

    QUESTION → CANDIDATES → RERANK → EVIDENCE → ANSWER → VALIDATED CITATIONS

An entry can only be created by :meth:`ValidatedAnswerCache.put`, and `put`
accepts a result only if :func:`is_publishable` holds — the answer was
generated by a provider, its citations resolved against the evidence set, the
grounding check passed, and the pipeline classified it `ANSWERED`. There is no
constructor here that takes prose. Nothing in this file can invent an answer,
and nothing in this file can promote a result the engine refused to publish.

**The gate runs twice.** `put` checks before writing and `get` checks again
after reading, so a hand-edited or corrupted JSON file cannot smuggle an
unvalidated answer back into the response path. A failed check drops the entry
and reports a miss; the caller then runs the real pipeline.

**Failure is always a miss.** An unreadable file, a bad key, a full disk — each
is recorded as a warning and degrades to "not cached", never to an exception.
A cache that cannot answer is invisible; a cache that raises would take the
demo down for a question the pipeline could have answered.

**Identity is part of the key.** The namespace passed in by `app/pipeline.py`
folds in the corpus fingerprint, the retrieval and reranking configuration and
the answering versions. Re-chunk the corpus, change the prompt, switch the
provider or turn the dense arm off and every existing entry stops matching,
because an answer produced against different evidence is a different answer.
"""
from __future__ import annotations

import copy
import hashlib
import json
import os
import tempfile
import threading
import time
from typing import Any, Mapping

from ai.retrieval.tokenizer import tokenize

#: On-disk shape. A file written by an older layout is ignored rather than
#: migrated: the entries are cheap to regenerate and a migration path is a
#: liability for something whose whole purpose is to be disposable.
CACHE_FORMAT = 1

DEFAULT_MAX_ENTRIES = 512

#: Default location. Deliberately outside `data/processed`, which the Docker
#: image copies in and the corpus owns, and outside `data/evaluation`, which
#: `.dockerignore` excludes. Created on first write.
DEFAULT_CACHE_PATH = os.path.join(
    os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
    "data", "cache", "validated_answers.json")

#: The seed cache: committed, shipped in the Docker image, never written to at
#: runtime. Render's filesystem is ephemeral, so a redeploy or an idle spin-down
#: takes the runtime file with it and the first person to click a demo question
#: pays for a completion again — on a free tier that may already be exhausted.
#: A file that travels inside the build artifact cannot be lost that way.
#:
#: It holds nothing the runtime cache does not: the same entries, produced by
#: the same pipeline, admitted by the same gate, re-validated on load. The only
#: difference is who may write it. `scripts/demo/warm_cache.py --seed-demo-cache`
#: generates it from real runs; the server only ever reads it.
DEFAULT_SEED_PATH = os.path.join(
    os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
    "data", "demo_cache", "validated_demo_answers.json")


def normalize_question(question: str) -> str:
    """The lookup form of a question: its tokens, in order, joined by spaces.

    Reusing `ai/retrieval/tokenizer.py` rather than inventing a second
    normalisation means the cache agrees with the index about what counts as
    the same question. Case, trailing punctuation, curly apostrophes, hyphens
    and the trade mark / trademark spelling all fold together, because the
    retriever already folds them and would have returned the same passages.
    Word order is preserved and nothing is stemmed or dropped, so two questions
    that differ in any content word remain different keys.

    An input that produces no tokens at all — punctuation only — falls back to
    collapsed lowercase text, so it still gets a stable key instead of colliding
    with every other such string.
    """
    tokens = tokenize(question or "")
    if tokens:
        return " ".join(tokens)
    return " ".join((question or "").lower().split())


def is_publishable(result: Any) -> bool:
    """Whether a pipeline result is one the system actually published.

    This is the entire admission policy, and it is a re-reading of decisions
    `ai/` already made — it re-checks flags, it does not re-derive them. Every
    condition must hold: an abstention, a provider failure, an ungrounded draft,
    a result with an unresolved citation and a result with no citation at all
    are each excluded by a separate clause, so no single wrong flag can let one
    through.
    """
    if not isinstance(result, Mapping):
        return False
    if result.get("status") != "ANSWERED":
        return False
    # A service failure and an ANSWERED status are contradictory; if they ever
    # appear together, the failure is the one to believe.
    if result.get("service_failure"):
        return False

    answer = result.get("answer")
    if not isinstance(answer, Mapping):
        return False
    if answer.get("insufficient_evidence"):
        return False
    if not answer.get("grounded"):
        return False
    if answer.get("validation_failures"):
        return False
    if answer.get("unsupported_claims"):
        return False
    if not str(answer.get("answer") or "").strip():
        return False
    if not (answer.get("citations") or ()):
        return False
    return True


class ValidatedAnswerCache:
    """Two layers, one gate.

    The **seed** layer is read-only and ships with the deployment; the
    **runtime** layer is writable and accumulates whatever the pipeline
    publishes while the server is up. A lookup reads runtime first, then seed,
    so a fresher answer to the same question always wins over the shipped one
    and the seed can never pin a stale result in place.

    Both layers go through :func:`is_publishable` on load and again on read.
    Being committed to the repository buys the seed no trust at all — it is
    checked exactly as strictly as a file the server wrote itself.

    Held behind its own lock. `app/pipeline.py` already serialises `answer()`,
    but the warm script and the health endpoint read this from other threads
    and the cost of being correct here is one uncontended acquire.
    """

    def __init__(self, *, namespace: str, path: str | None = DEFAULT_CACHE_PATH,
                 seed_path: str | None = DEFAULT_SEED_PATH,
                 max_entries: int = DEFAULT_MAX_ENTRIES):
        self.namespace = namespace
        self.path = path
        self.seed_path = seed_path
        self.max_entries = max(1, int(max_entries))
        self.warnings: list[str] = []
        self.hits = 0
        self.seed_hits = 0
        self.misses = 0
        self.stores = 0
        self.rejections = 0
        self._lock = threading.Lock()
        self._entries: dict[str, dict[str, Any]] = {}
        #: Read-only. Never written, never evicted, never saved back.
        self._seed: dict[str, dict[str, Any]] = {}
        #: Entries belonging to another namespace. Never read, never served,
        #: only carried through on save. Starting the server once with a
        #: different flag — `--provider extractive` to rehearse offline, say —
        #: would otherwise erase a cache that cost real provider requests to
        #: warm, which is the opposite of what this module is for.
        self._foreign: dict[str, dict[str, Any]] = {}
        self._load_seed()
        self._load()

    # -- keys ----------------------------------------------------------------

    def key(self, question: str) -> str:
        """Namespace and normalised question, hashed together.

        Hashed rather than concatenated so the key is fixed-length and safe as a
        JSON object member, and so an entry written under one corpus or prompt
        version can never be read under another — the namespace is inside the
        digest, not beside it.
        """
        material = f"{self.namespace}\x00{normalize_question(question)}"
        return hashlib.sha256(material.encode("utf-8")).hexdigest()[:32]

    # -- read ----------------------------------------------------------------

    def get(self, question: str) -> dict[str, Any] | None:
        """A stored entry for this question, or `None`.

        Runtime before seed: an answer this server produced is at least as
        current as the one that shipped with it, and the seed must never
        override a fresher result.

        The returned payload is a deep copy carrying a `source` of `"runtime"`
        or `"seed"`: the caller stamps its own timings and cache metadata onto
        it, and must not be able to mutate the entry every later request will
        be served from.
        """
        try:
            entry_key = self.key(question)
        except Exception as exc:  # noqa: BLE001 - a bad key is a miss, not a 500
            self._warn(f"cache key failed ({type(exc).__name__}); treating as a miss")
            return None

        with self._lock:
            for source, layer in (("runtime", self._entries), ("seed", self._seed)):
                entry = layer.get(entry_key)
                if entry is None:
                    continue
                if entry.get("namespace") != self.namespace or not is_publishable(
                        entry.get("result")):
                    # Second reading of the gate. Reachable only if a file was
                    # edited by hand or corrupted — which is exactly when it
                    # matters, and is why the shipped seed gets no exemption.
                    layer.pop(entry_key, None)
                    self.rejections += 1
                    self._warn(f"a {source} cache entry failed re-validation on "
                               f"read and was discarded; the pipeline will "
                               f"answer this question")
                    continue
                self.hits += 1
                if source == "seed":
                    self.seed_hits += 1
                served = copy.deepcopy(entry)
                served["source"] = source
                return served
            self.misses += 1
            return None

    # -- write ---------------------------------------------------------------

    def put(self, question: str, result: Mapping[str, Any]) -> bool:
        """Store a published result. Returns whether it was stored.

        Refusal is the common case and is not an error: an abstention, a rate
        limit and an ungrounded draft all arrive here and all leave unstored.
        """
        if not is_publishable(result):
            return False
        # Imported here, not at module scope: `app.config` imports
        # `app.pipeline`, which imports this module, so a top-level import of
        # `app.schemas` would close a cycle. It is the same function either way.
        from app.schemas import to_jsonable

        try:
            entry = {
                "namespace": self.namespace,
                "question": str(result.get("question") or question),
                "normalized": normalize_question(question),
                "cached_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
                "result": to_jsonable(result),
            }
            entry_key = self.key(question)
        except Exception as exc:  # noqa: BLE001 - never fail a good answer
            self._warn(f"cache write skipped ({type(exc).__name__})")
            return False

        with self._lock:
            self._entries[entry_key] = entry
            while len(self._entries) > self.max_entries:
                self._entries.pop(next(iter(self._entries)))
            self.stores += 1
            self._save()
        return True

    # -- inspection ----------------------------------------------------------

    def questions(self) -> list[str]:
        """Questions this cache can answer, runtime first, without duplicates."""
        with self._lock:
            seen = {k: e.get("question", "") for k, e in self._seed.items()}
            seen.update({k: e.get("question", "") for k, e in self._entries.items()})
            return list(seen.values())

    def seed_questions(self) -> list[str]:
        with self._lock:
            return [e.get("question", "") for e in self._seed.values()]

    def stats(self) -> dict[str, Any]:
        with self._lock:
            return {
                "enabled": True,
                "entries": len(self._entries) + len(self._seed),
                "runtime_entries": len(self._entries),
                "seed_entries": len(self._seed),
                "hits": self.hits,
                "seed_hits": self.seed_hits,
                "misses": self.misses,
                "stores": self.stores,
                "rejected_on_read": self.rejections,
                "namespace": self.namespace,
                "path": self.path,
                "seed_path": self.seed_path,
                "warnings": list(self.warnings),
            }

    # -- persistence ---------------------------------------------------------

    def _warn(self, message: str) -> None:
        if message not in self.warnings:
            self.warnings.append(message)

    def _read_document(self, path: str, label: str) -> dict[str, Any] | None:
        """One cache file, parsed and format-checked. `None` on any problem."""
        if not path or not os.path.isfile(path):
            return None
        try:
            with open(path, encoding="utf-8") as handle:
                document = json.load(handle)
        except Exception as exc:  # noqa: BLE001 - a broken file is not fatal
            self._warn(f"{label} cache file unreadable ({type(exc).__name__}); ignored")
            return None
        if not isinstance(document, dict) or document.get("format") != CACHE_FORMAT:
            self._warn(f"{label} cache file has an unrecognised format; ignored")
            return None
        entries = document.get("entries")
        if not isinstance(entries, dict):
            self._warn(f"{label} cache file has no entries object; ignored")
            return None
        return document

    def _load_seed(self) -> None:
        """Read the shipped seed. Read-only, and trusted no further than any file.

        A seed built against a different corpus, prompt or provider is reported
        rather than skipped in silence: it is the one failure mode of a shipped
        cache that looks exactly like an empty one, and the startup log is
        where somebody can still act on it.
        """
        document = self._read_document(self.seed_path or "", "seed")
        if document is None:
            return
        kept: dict[str, dict[str, Any]] = {}
        wrong_namespace = 0
        rejected = 0
        for entry_key, entry in document["entries"].items():
            if not isinstance(entry, dict):
                rejected += 1
                continue
            if entry.get("namespace") != self.namespace:
                wrong_namespace += 1
                continue
            if not is_publishable(entry.get("result")):
                rejected += 1
                continue
            kept[str(entry_key)] = entry
        if wrong_namespace:
            self._warn(
                f"{wrong_namespace} seed answer(s) were built for a different "
                f"corpus, prompt or provider and cannot be served; regenerate "
                f"with scripts/demo/warm_cache.py --seed-demo-cache in the "
                f"configuration you deploy")
        if rejected:
            self._warn(f"{rejected} seed answer(s) failed validation on load "
                       f"and were dropped")
        self._seed = kept

    def _load(self) -> None:
        """Read the writable runtime file. Any problem leaves it empty."""
        document = self._read_document(self.path or "", "runtime")
        if document is None:
            return
        entries = document["entries"]

        kept: dict[str, dict[str, Any]] = {}
        foreign: dict[str, dict[str, Any]] = {}
        for entry_key, entry in entries.items():
            if not isinstance(entry, dict):
                continue
            # An entry from another corpus, prompt or provider is never served:
            # it answers a question this build was not asked. It is kept in the
            # file, though, so switching a flag and switching back does not
            # cost the provider requests that warmed it.
            if entry.get("namespace") != self.namespace:
                foreign[str(entry_key)] = entry
                continue
            if not is_publishable(entry.get("result")):
                continue
            kept[str(entry_key)] = entry
        if foreign:
            self._warn(f"{len(foreign)} cache entr{'y' if len(foreign) == 1 else 'ies'} "
                       f"belong to a different corpus, prompt or provider; kept "
                       f"in the file but not served")
        self._entries = kept
        self._foreign = foreign

    def _save(self) -> None:
        """Write the whole file atomically. Called with the lock held."""
        if not self.path:
            return
        document = {"format": CACHE_FORMAT, "namespace": self.namespace,
                    "entries": {**self._foreign, **self._entries}}
        try:
            directory = os.path.dirname(self.path) or "."
            os.makedirs(directory, exist_ok=True)
            # Same directory, so `os.replace` is a rename within one filesystem
            # and a reader sees either the old file or the new one, never half.
            handle = tempfile.NamedTemporaryFile(
                "w", encoding="utf-8", dir=directory, prefix=".answers-",
                suffix=".tmp", delete=False)
            try:
                with handle:
                    json.dump(document, handle, ensure_ascii=False, indent=2)
                os.replace(handle.name, self.path)
            except Exception:
                try:
                    os.unlink(handle.name)
                except OSError:
                    pass
                raise
        except Exception as exc:  # noqa: BLE001 - memory cache still works
            self._warn(f"cache file could not be written ({type(exc).__name__}); "
                       f"entries are kept in memory only")
